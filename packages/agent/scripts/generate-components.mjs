#!/usr/bin/env node
/**
 * Writes src/components.generated.ts from Kernel's registry
 * (packages/registry/dist/registry.json), so a snapshot can name the Kernel
 * component behind a node ("Switch", "TagInput") from its `kernel-<Name>-*`
 * class or `kernel-*` tag, for exactly the components this version ships.
 * The output is committed so typecheck works before a build; the build
 * regenerates it, and a stale copy shows up as a git diff.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");

let components;
try {
  components = JSON.parse(readFileSync(join(pkg, "..", "registry", "dist", "registry.json"), "utf8")).components;
} catch {
  console.error("[agent] Run `bun run build` in ../registry first (produces dist/registry.json).");
  process.exit(1);
}

// React's CSS Modules and the elements package's kernelClass() both emit
// `kernel-<Folder>-<part>`, and the folder is the component's first export.
const names = [];
const tags = {};
for (const c of components) {
  const name = c.reactExports?.[0];
  if (!name) continue;
  names.push(name);
  for (const tag of [c.elementTag, ...(c.elementSubTags ?? [])].filter(Boolean)) tags[tag] = name;
}
names.sort();

const out =
  `// Generated by scripts/generate-components.mjs from Kernel's registry. Do not edit.\n\n` +
  `/** Kernel component names, as used in \`kernel-<Name>-<part>\` class names. */\n` +
  `export const KERNEL_COMPONENTS: ReadonlySet<string> = new Set(${JSON.stringify(names, null, 2)});\n\n` +
  `/** Custom element tag → Kernel component name. */\n` +
  `export const KERNEL_TAGS: Readonly<Record<string, string>> = ${JSON.stringify(tags, null, 2)};\n`;

writeFileSync(join(pkg, "src", "components.generated.ts"), out);
console.log(`[agent] wrote src/components.generated.ts (${names.length} components, ${Object.keys(tags).length} tags)`);
