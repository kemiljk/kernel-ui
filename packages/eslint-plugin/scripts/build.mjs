#!/usr/bin/env node
/**
 * Builds dist/: copies the rules and generates dist/data.js from the
 * registry's API extraction (packages/registry/dist/api.json), so the
 * published plugin knows every Kernel component's exact props for the
 * version it ships with and needs no runtime dependencies.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const registryDist = join(pkg, "..", "registry", "dist");

let api;
let registry;
try {
  api = JSON.parse(readFileSync(join(registryDist, "api.json"), "utf8")).components;
  registry = JSON.parse(readFileSync(join(registryDist, "registry.json"), "utf8")).components;
} catch {
  console.error("[eslint-plugin] Run `bun run build` in ../registry first (produces dist/api.json).");
  process.exit(1);
}

// Export name → { props, extends } for every React component.
const PROPS = {};
for (const entry of Object.values(api)) {
  for (const [name, info] of Object.entries(entry.react)) {
    PROPS[name] = { props: info.props.map(({ name, type }) => ({ name, type })), extends: info.extends };
  }
}

const REPLACEMENTS = registry
  .filter((c) => c.status === "available")
  .map((c) => ({ component: c.reactExports[0], url: c.docsUrl, shadcn: c.shadcnAliases ?? [], radix: c.radixPackages ?? [] }));

/** Props other libraries use, with Kernel's name for the same idea. */
const FOREIGN_PROPS = {
  asChild: "`render={<a href=… />}` (Kernel uses a render prop, not asChild)",
  leftIcon: "`iconStart`",
  startIcon: "`iconStart`",
  leftSection: "`iconStart`",
  startContent: "`iconStart`",
  rightIcon: "`iconEnd`",
  endIcon: "`iconEnd`",
  rightSection: "`iconEnd`",
  endContent: "`iconEnd`",
  isDisabled: "`disabled`",
  isLoading: "`loading`",
  isInvalid: "`invalid`",
  isRequired: "`required`",
  colorScheme: "`variant`",
  intent: "`variant`",
  helperText: "`description`",
  helpText: "`description`",
  onValueChanged: "`onValueChange`",
};

const FIELD_COMPONENTS = ["TextField", "Textarea", "Select", "Combobox", "TagInput", "NumberField", "ColorPicker", "Slider", "FileUpload"];

mkdirSync(join(pkg, "dist"), { recursive: true });
const { version } = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8"));
writeFileSync(join(pkg, "dist", "index.js"), readFileSync(join(pkg, "src", "index.js"), "utf8").replace("__VERSION__", version));
writeFileSync(
  join(pkg, "dist", "data.js"),
  `// Generated by scripts/build.mjs from Kernel's registry. Do not edit.\n` +
    `export const PROPS = ${JSON.stringify(PROPS)};\n` +
    `export const REPLACEMENTS = ${JSON.stringify(REPLACEMENTS)};\n` +
    `export const FOREIGN_PROPS = ${JSON.stringify(FOREIGN_PROPS, null, 2)};\n` +
    `export const FIELD_COMPONENTS = ${JSON.stringify(FIELD_COMPONENTS)};\n`,
);
console.log(`[eslint-plugin] built dist/ with props for ${Object.keys(PROPS).length} components`);
