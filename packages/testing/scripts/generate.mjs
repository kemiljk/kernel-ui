#!/usr/bin/env node
/**
 * Generates src/generated/registry.ts from Kernel's component registry, so the
 * published package knows every component's name, slug, custom element tag
 * and class-name folder for the version it ships with, with no runtime
 * dependency on the registry.
 *
 * Reads packages/registry/dist/registry.json (built by `bun run build` in
 * packages/registry), falling back to the committed copy the docs site serves
 * (apps/docs/public/registry.json). The output is committed so the package
 * typechecks and tests without a build; `tests/registry.test.ts` fails when it
 * drifts from the registry.
 */
import { existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const repo = join(pkg, "..", "..");
const sources = [join(repo, "packages/registry/dist/registry.json"), join(repo, "apps/docs/public/registry.json")];
const source = sources.find((file) => existsSync(file));
if (!source) {
  console.error("[testing] No registry.json found. Run `bun run build` in packages/registry first.");
  process.exit(1);
}

const registry = JSON.parse(readFileSync(source, "utf8")).components.filter((c) => c.status === "available");
const componentsDir = join(repo, "packages/react/src/components");
const isDir = (path) => existsSync(path) && statSync(path).isDirectory();

const entries = registry.map((c) => {
  const candidates = [c.name.replace(/[^A-Za-z]/g, ""), ...c.reactExports];
  const folder = candidates.find((name) => isDir(join(componentsDir, name))) ?? candidates[0];
  return {
    name: c.name,
    export: c.reactExports[0],
    slug: c.slug,
    folder,
    tag: c.elementTag,
    subTags: c.elementSubTags ?? [],
  };
});

const out = `// Generated by scripts/generate.mjs from Kernel's registry. Do not edit.
export interface RegistryComponent {
  /** Display name, e.g. "Dropdown Menu". */
  name: string;
  /** The primary React export, e.g. "DropdownMenu". */
  export: string;
  slug: string;
  /** The folder in Kernel's class names: \`kernel-<folder>-<part>\`. */
  folder: string;
  /** The custom element tag in @kernelui-lib/elements. */
  tag: string;
  subTags: string[];
}

export const REGISTRY: RegistryComponent[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(pkg, "src/generated/registry.ts"), out);
console.log(`[testing] generated src/generated/registry.ts (${entries.length} components)`);
